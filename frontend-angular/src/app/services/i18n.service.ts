function readStoredLocale(): LocaleCode {
  if (typeof window === 'undefined') {
    return 'es_419';
  }
  const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
  return stored === 'en_US' ? 'en_US' : 'es_419';
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  private localeSubject = new BehaviorSubject<LocaleCode>(readStoredLocale());
  locale$ = this.localeSubject.asObservable();

  constructor() {
    this.locale$.subscribe(() => this.syncDocument());
  }

  get currentLocale(): LocaleCode {
    return this.localeSubject.value;
  }

  get intlLocale(): string {
    return this.currentLocale === 'en_US' ? 'en-US' : 'es-PE';
  }

  setLocale(locale: LocaleCode): void {
    this.localeSubject.next(locale);
    if (typeof window !== 'undefined') {
      localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    }
  }

  toggleLocale(): void {
    this.setLocale(this.currentLocale === 'es_419' ? 'en_US' : 'es_419');
  }

  private syncDocument(): void {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = this.currentLocale === 'en_US' ? 'en' : 'es';
    document.title = this.t('meta.title');
  }

  /** Traduce una clave simple. */
  t(key: string): string {
    return TRANSLATIONS[this.currentLocale][key] || TRANSLATIONS.es_419[key] || key;
  }

  /** Traduce e interpola parametros tipo {nombre} dentro del texto. */
  tn(key: string, params: Record<string, string | number | null | undefined>): string {
    let text = this.t(key);
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v == null ? '' : String(v));
    }
    return text;
  }

  /** Traduce datos con codigo estable (recompensas, retos, insignias); si no hay traduccion, usa el valor original. */
  tc(group: string, code: string | number, field: string, fallback: string): string {
    const key = `${group}.${code}.${field}`;
    const value = this.t(key);
    return value === key ? fallback : value;
  }

  /** Elige singular o plural segun el conteo. */
  plural(count: number, singularKey: string, pluralKey: string): string {
    return count === 1 ? this.t(singularKey) : this.t(pluralKey);
  }

  formatDate(value: string | Date | null | undefined, options?: Intl.DateTimeFormatOptions): string {
    if (!value) return '';
    const date = typeof value === 'string' ? new Date(value) : value;
    if (isNaN(date.getTime())) return '';
    return new Intl.DateTimeFormat(
      this.intlLocale,
      options || { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' }
    ).format(date);
  }

  formatNumber(value: number, options?: Intl.NumberFormatOptions): string {
    return new Intl.NumberFormat(this.intlLocale, options).format(value);
  }
}
